    """Конфигурация сбора и анализа."""

    # --- охват -------------------------------------------------------------
    chain: str = "bsc"
    """Сеть DEX. Идентификатор в терминах GeckoTerminal: bsc, eth, arbitrum..."""

    quote_asset: str = "USDT"
    """Стартовый и конечный актив всех связок."""

