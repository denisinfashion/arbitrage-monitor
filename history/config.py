WATCHLIST_FILE = BASE_DIR / "watchlist.txt"
"""Список наблюдения в виде обычного файла рядом с проектом.

Правка YAML ради добавления одного тикера — плохой обмен: файл workflow
легко испортить отступом, а ошибка вылезет только при следующем прогоне.
Простой текстовый файл правится без риска и виден в интерфейсе.
"""


def load_watchlist(settings=None) -> List[str]:
    """Тикеры для принудительного наблюдения из всех трёх источников.

    Порядок: файл `watchlist.txt`, переменная окружения `ARB_WATCH_TOKENS`,
    поле настроек. Источники складываются, а не заменяют друг друга —
    иначе добавление тикера в одном месте молча выключало бы другое.
    """
    out: List[str] = []

    def add(value: str) -> None:
        token = value.split("#", 1)[0].strip().upper()
        if token and token not in out:
            out.append(token)

    try:
        if WATCHLIST_FILE.exists():
            for line in WATCHLIST_FILE.read_text(encoding="utf-8").splitlines():
                add(line)
    except OSError:
        pass

    for chunk in os.environ.get("ARB_WATCH_TOKENS", "").split(","):
        add(chunk)

    for chunk in getattr(settings or SETTINGS, "watch_tokens", None) or []:
        add(str(chunk))

    return out


